import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve, relative, sep } from 'node:path';

// The application is native ESM: production assets are also the readable source.
const root = resolve('dist');
async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory()
          ? walk(resolve(directory, entry.name))
          : [resolve(directory, entry.name)],
      ),
    )
  ).flat();
}
const files = (await walk(root)).filter((path) => !path.endsWith('service-worker.js')).sort();
const hash = createHash('sha256');
for (const file of files) {
  hash.update(relative(root, file));
  hash.update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 16);
const assets = files.map((file) => './' + relative(root, file).split(sep).join('/'));
const source = `/* Generated by scripts/build.mjs. Cache only this application's static assets. */
const CACHE = 'millennium-static-${version}';
const ASSETS = ${JSON.stringify(assets, null, 2)};
self.addEventListener('install', event => event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting())));
self.addEventListener('activate', event => event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('millennium-static-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim())));
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin) return;
  const relative = './' + url.pathname.slice(new URL(self.registration.scope).pathname.length);
  if (event.request.mode === 'navigate' && (relative === './' || relative === './index.html')) {
    event.respondWith(fetch(event.request).catch(() => caches.open(CACHE).then(cache => cache.match('./index.html'))));
  } else if (ASSETS.includes(relative)) {
    event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(event.request, { ignoreSearch: true })) || fetch(event.request)));
  }
});
`;
await writeFile(resolve(root, 'service-worker.js'), source);
console.log(`Static production assets: ${files.length} files. Offline cache version: ${version}.`);
